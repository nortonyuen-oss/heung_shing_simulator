#!/usr/bin/env node
// The official site's art (docs/site-redesign-spec.md §6): the game's own illustrations and characters,
// resized into docs/assets/site/ as WebP, and the 18 chapters' places on the chart computed with the
// game's own code (hk-district-maps.js + map-sources.js getDistrictOverviewBox), written to
// docs/site-campaign.js.
//
//   node scripts/build-site-assets.js
//
// Sources stay where they are; re-run after any of them changes.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const sharp = require('sharp');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'assets', 'site');

const IMAGES = [
  // [source, output, width]
  ['UI/campaign/select-backdrop.webp', 'hero.webp', 1600],
  ['UI/news/phase0.webp', 'letter.webp', 900],
  ['UI/hk-district-overview.webp', 'chart.webp', 1062],
  ['UI/campaign/events/tramway.webp', 'feature-tram.webp', 800],
  ['UI/campaign/events/singerBirthday.webp', 'feature-festival.webp', 800],
  ['build/icon-rounded.png', 'icon.webp', 160],
  ...['secretary.png', 'queen.png', 'aviation.webp', 'foodie.webp', 'uncleBus.webp', 'villager.webp', 'tycoon.webp', 'scientist.webp',
    'mayorLook1.webp', 'mayorLook2.webp', 'mayorLook3.webp', 'mayorLook4.webp', 'mayorLook5.webp', 'mayorLook6.webp']
    .map((file) => [`UI/campaign/portraits/${file}`, `people/${file.replace(/\.(png|webp)$/, '.webp')}`, 256]),
  ...Array.from({ length: 18 }, (_, i) => {
    const id = `ch${String(i + 1).padStart(2, '0')}`;
    return [`UI/campaign/chapters/${id}.webp`, `chapters/${id}.webp`, 800];
  }),
];

function loadGame(files, expose) {
  const context = { console };
  vm.createContext(context);
  vm.runInContext(files.map((file) => fs.readFileSync(path.join(ROOT, file), 'utf8')).join('\n;\n') + `\n;${expose}`, context);
  return context;
}

async function main() {
  let bytes = 0;
  for (const [source, output, width] of IMAGES) {
    const target = path.join(OUT, output);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    await sharp(path.join(ROOT, source)).resize({ width, withoutEnlargement: true }).webp({ quality: 80, effort: 6 }).toFile(target);
    bytes += fs.statSync(target).size;
  }

  // the chart's pins, as the game's chapter map places them (campaign.js getChapterPin)
  // (only getDistrictOverviewBox from map-sources.js: the rest of that file needs the whole game)
  const sources = fs.readFileSync(path.join(ROOT, 'map-sources.js'), 'utf8');
  const boxSource = sources.slice(sources.indexOf('function getDistrictOverviewBox('), sources.indexOf('\n}\n', sources.indexOf('function getDistrictOverviewBox(')) + 3);
  const game = loadGame(['hk-district-maps.js'], `${boxSource}\nthis.MAPS = HK_DISTRICT_MAPS; this.box = getDistrictOverviewBox;`);
  const campaign = require(path.join(ROOT, 'campaign-chapters.js'));
  const campaignRuntime = fs.readFileSync(path.join(ROOT, 'campaign.js'), 'utf8');
  const offsets = JSON.parse(campaignRuntime.match(/const CAMPAIGN_PIN_OFFSETS = (\{[^\n]*\});/)[1].replace(/(\w+):/g, '"$1":'));
  const chapters = campaign.CAMPAIGN_CHAPTERS.map((chapter) => {
    const map = game.MAPS.find((entry) => entry.id === chapter.mapId);
    const offset = offsets[chapter.id] || {};
    const pin = game.box({ centre: { e: map.centre.e + (offset.de || 0), n: map.centre.n + (offset.dn || 0) } });
    return {
      id: chapter.id, number: chapter.number,
      district: chapter.district, title: chapter.title,
      x: Math.round(pin.x * 100) / 100, y: Math.round(pin.y * 100) / 100,
      board: `assets/site/chapters/${chapter.id}.webp`,
    };
  });
  const data = `// Generated by scripts/build-site-assets.js from the game's campaign data - do not edit.\n`
    + `const SITE_CAMPAIGN_CHAPTERS = ${JSON.stringify(chapters, null, 1)};\n`;
  fs.writeFileSync(path.join(ROOT, 'docs', 'site-campaign.js'), data);
  console.log(`${IMAGES.length} images, ${(bytes / 1048576).toFixed(2)} MiB -> docs/assets/site; ${chapters.length} chapters -> docs/site-campaign.js`);
}

main().catch((error) => { console.error(error); process.exitCode = 1; });
