#!/usr/bin/env node

// Downloads the Hong Kong Observatory's Gregorian-Lunar calendar conversion tables (公曆與農曆日期
// 對照表, one text file a year, 1901-2100) and writes festival-lunar-data.js: for every year, the
// Gregorian dates of the lunar dates the festivals hang on (docs/festival-dlc-design.md §2). Run
// it by hand; the game never needs the internet for this.
//
//   node scripts/sync-lunar-calendar.js [--cache <dir>]
//
// The tables print the first day of each lunar month as the month's name (正月, 二月, 閏四月 ...)
// and every other day as its day (初二 ... 三十). Leap months are skipped: 閏五月初五 is not 端午.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT_PATH = path.join(ROOT, 'festival-lunar-data.js');
const FIRST_YEAR = 1901;
const LAST_YEAR = 2100;
const SOURCE_URL = (year) => `https://www.hko.gov.hk/tc/gts/time/calendar/text/files/T${year}c.txt`;

// [key, lunar month, lunar day]
const LUNAR_DATES = Object.freeze([
  ['newYear', 1, 1],      // 正月初一
  ['dragonBoat', 5, 5],   // 五月初五
  ['ghost', 7, 14],       // 七月十四
  ['midAutumn', 8, 15],   // 八月十五
]);

const args = process.argv.slice(2);
const cacheIndex = args.indexOf('--cache');
const CACHE_DIR = cacheIndex >= 0 ? path.resolve(args[cacheIndex + 1]) : null;

const MONTH_NAMES = ['正', '二', '三', '四', '五', '六', '七', '八', '九', '十', '十一', '十二'];
const DIGITS = { 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9 };

// 初一..初十, 十一..十九, 二十, 廿一..廿九, 三十
function parseLunarDay(text) {
  if (text === '初十') return 10;
  if (text === '二十') return 20;
  if (text === '三十') return 30;
  const [head, tail] = [text[0], text.slice(1)];
  if (head === '初' && DIGITS[tail]) return DIGITS[tail];
  if (head === '十' && DIGITS[tail]) return 10 + DIGITS[tail];
  if (head === '廿' && DIGITS[tail]) return 20 + DIGITS[tail];
  return null;
}

// '正月' -> { month: 1, leap: false }; '閏四月' -> { month: 4, leap: true }; a day -> null
function parseLunarMonth(text) {
  const match = /^(閏)?(.+)月$/.exec(text);
  if (!match) return null;
  const month = MONTH_NAMES.indexOf(match[2]) + 1;
  return month ? { month, leap: !!match[1] } : null;
}

/**
 * The Gregorian dates of LUNAR_DATES in one year's table.
 * @param {string} text the HKO table (UTF-8)
 * @param {number} year
 * @returns {Object<string, [number, number]>} key -> [month, day]
 */
function parseYearTable(text, year) {
  const found = {};
  let lunar = null; // { month, leap, day } of the current row
  let rows = 0;
  for (const line of String(text).replace(/^﻿/, '').split(/\r?\n/)) {
    const match = /^(\d{4})年(\d{1,2})月(\d{1,2})日\s+(\S+)/.exec(line.trim());
    if (!match) continue;
    const [, y, m, d, cell] = match;
    if (Number(y) !== year) throw new Error(`${year}: row for ${y} in the table`);
    rows += 1;
    const monthStart = parseLunarMonth(cell);
    if (monthStart) {
      lunar = { ...monthStart, day: 1 };
    } else {
      const day = parseLunarDay(cell);
      if (day == null) throw new Error(`${year}-${m}-${d}: unreadable lunar day "${cell}"`);
      // before the year's first month name the month is unknown (last year's 11th/12th)
      lunar = lunar ? { ...lunar, day } : null;
      if (lunar && day === 1) throw new Error(`${year}-${m}-${d}: 初一 without a month name`);
    }
    if (!lunar || lunar.leap) continue;
    LUNAR_DATES.forEach(([key, lm, ld]) => {
      if (lunar.month === lm && lunar.day === ld) found[key] = [Number(m), Number(d)];
    });
  }
  const daysInYear = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0 ? 366 : 365;
  if (rows !== daysInYear) throw new Error(`${year}: ${rows} rows, expected ${daysInYear}`);
  const missing = LUNAR_DATES.map(([key]) => key).filter((key) => !found[key]);
  if (missing.length) throw new Error(`${year}: no ${missing.join(', ')}`);
  return found;
}

async function readYear(year) {
  const cached = CACHE_DIR && path.join(CACHE_DIR, `T${year}c.txt`);
  if (cached && fs.existsSync(cached)) return fs.readFileSync(cached, 'utf8');
  const response = await fetch(SOURCE_URL(year));
  if (!response.ok) throw new Error(`${SOURCE_URL(year)}: HTTP ${response.status}`);
  const text = await response.text();
  if (cached) {
    fs.mkdirSync(CACHE_DIR, { recursive: true });
    fs.writeFileSync(cached, text);
  }
  return text;
}

const pad = (n) => String(n).padStart(2, '0');

async function main() {
  const rows = [];
  for (let year = FIRST_YEAR; year <= LAST_YEAR; year++) {
    const found = parseYearTable(await readYear(year), year);
    rows.push(LUNAR_DATES.map(([key]) => `${pad(found[key][0])}${pad(found[key][1])}`).join(' '));
    if (year % 20 === 0) console.log(`${year} ok`);
  }
  const body = [
    '// Generated by scripts/sync-lunar-calendar.js from the Hong Kong Observatory\'s Gregorian-Lunar',
    '// calendar conversion tables. Do not edit by hand.',
    '//',
    `// rows[year - firstYear] = '${LUNAR_DATES.map(([key]) => key).join(' ')}', each the Gregorian MMDD`,
    '// of 正月初一, 五月初五, 七月十四 and 八月十五 (never a leap month).',
    'const FESTIVAL_LUNAR_DATA = Object.freeze({',
    `  source: ${JSON.stringify(SOURCE_URL('YYYY'))},`,
    `  firstYear: ${FIRST_YEAR},`,
    `  keys: Object.freeze(${JSON.stringify(LUNAR_DATES.map(([key]) => key))}),`,
    '  rows: Object.freeze([',
    ...rows.map((row, i) => `    '${row}', // ${FIRST_YEAR + i}`),
    '  ]),',
    '});',
    "if (typeof module !== 'undefined' && module.exports) module.exports = { FESTIVAL_LUNAR_DATA };",
    '',
  ].join('\n');
  fs.writeFileSync(OUTPUT_PATH, body);
  console.log(`${rows.length} years -> ${path.relative(ROOT, OUTPUT_PATH)}`);
}

if (require.main === module) {
  main().catch((error) => { console.error(error); process.exit(1); });
}

module.exports = { parseYearTable, parseLunarDay, parseLunarMonth };
